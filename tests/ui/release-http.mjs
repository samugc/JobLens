import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import vm from 'node:vm';
const require=createRequire(import.meta.url);
const cv=require('../../web/workspace/api-adapter.js');
const pa=require('../../web/workspace/profile-adapter.js');
const review=require('../../web/workspace/profile-review.js');
globalThis.JobLensProfileAdapter=pa;
const [origin,pdf,docx]=process.argv.slice(2);
const calls=[];
const fetchImpl=async(url,options)=>{
 assert.equal(new URL(url).origin,origin);calls.push(url);
 return fetch(url,{...options,headers:{...options.headers,Origin:origin}});
};
const api=new cv.CvApiAdapter({baseUrl:origin+'/api/cv',fetchImpl});
const job=await api.createExtraction([new File([readFileSync(pdf)],'fictional.pdf'),new File([readFileSync(docx)],'fictional.docx')]);
const profile=await new pa.CvProfileAdapter({baseUrl:origin+'/api/cv',fetchImpl}).createProfile(job);
let state=review.createReviewState(profile);
for(const p of profile.proposals) if(!p.conflicts.length) state=review.applyReviewAction(state,{kind:'approve',proposalId:p.id}).state;
const app=readFileSync(new URL('../../web/workspace/app.js',import.meta.url),'utf8');
const fn=app.slice(app.indexOf('  function buildApprovedProfilePayload()'),app.indexOf('  async function exportApprovedProfile()'));
const ctx={state:{profile:{profile},review:state,job,profileView:review.buildViewModel(profile,state,pa)}};
vm.createContext(ctx);vm.runInContext(fn+'; result=buildApprovedProfilePayload();',ctx);
writeFileSync('.integration-verification/js-profile.json',JSON.stringify({profile:ctx.result,source:pa.buildProfileRequest(job)}));
let approved=(await api.validateApprovedProfile(job,ctx.result)).approved_profile;
approved=(await api.validateApprovedProfile(null,JSON.parse(JSON.stringify(approved)))).approved_profile;
let {draft}=await api.generateDraft(approved,{text:'AI Engineer required Python SQL Kubernetes. Build reliable data pipelines.'},approved.source);
draft.candidate.full_name='Alex Example';
for(const s of draft.sections)for(const i of s.items) draft=(await api.approveDraftItem(draft,i.item_id)).draft;
const item=draft.sections[0].items[0];
draft=(await api.editDraftItem(draft,item.item_id,item.text+' ')).draft;
assert.equal(draft.sections[0].items[0].review_status,'needs_review');
draft=(await api.approveDraftItem(draft,item.item_id)).draft;
assert.equal((await api.exportPdf(draft,approved)).type,'application/pdf');
assert.equal((await api.exportDocx(draft,approved)).type,'application/vnd.openxmlformats-officedocument.wordprocessingml.document');
assert.equal((app.match(/async function exportTailor\(/g)||[]).length,1);
console.log('PASS: real JS adapters + served profile builder + private save/import + generation/edit/review + PDF/DOCX; '+calls.length+' same-origin requests');
